def _csr(triples, shape):
    r, c, v = zip(*triples)
    return sp.csr_matrix((v, (r, c)), shape=shape)


@pytest.mark.smoke
def test_branching_on_a_value_past_its_bound_terminates():
    n = len(C)
    r = solve_milp(
        np.array(C),
        A_ub=_csr(A_UB, A_UB_SHAPE),
        b_ub=np.array(B_UB),
        A_eq=_csr(A_EQ, A_EQ_SHAPE),
        b_eq=np.array(B_EQ),
        bounds=[(0.0, np.inf)] * n,
        integrality=np.array(INTEGRALITY),
        gap_tolerance=GAP,
        # Deterministic work cap, well above the ~14k nodes the fixed search needs;
        # the unfixed search spends it all on one repeated decision.
        max_nodes=200_000,
        time_limit=120.0,  # backstop only
    )
    assert r.status.value == "optimal", (r.status, r.node_count)
    assert r.node_count < 200_000
    assert r.objective == pytest.approx(HIGHS_OPT, rel=1e-4, abs=1e-6)
