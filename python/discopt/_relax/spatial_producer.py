"""Producer: extract a native-kernel ``SpatialKernelSpec`` from a discopt model.

The Rust spatial B&B kernel (``discopt-core::bnb::spatial_*``, issue #764) runs a
node entirely in Rust — patch box-dependent McCormick envelopes, assemble the node
LP, warm-solve, OBBT-sweep — given the *box-independent* relaxation structure once.
This module produces that structure from the uniform factorable relaxation
(``uniform_relax.build_uniform_relaxation``), which registers every lifted term with
its operand/output columns and emits the McCormick / secant-tangent envelope rows.

Classification (validated on tanksize, #764): a row is a term's **envelope** (box
dependent, regenerated by the Rust kernel per node) iff its support is contained in
that term's ``{operands, aux}`` columns AND the term claims exactly the envelope's
row count; every other row — the model's linear constraints and the
linear-definitional rows of factorable intermediate aux columns — is
**box-independent** and passed through as a fixed row. The row-count condition is
load-bearing: a lifted model constraint over a term's own variables has the same
support (``x0*x1 >= 60`` becomes ``{aux: -1} <= -60``), and claiming it as an
envelope drops it from the node LP entirely (#861). Auxiliary-column bounds
come from the relaxation's own interval propagation (finite), which the safe-bound
evaluation requires.

Covered term families: bilinear products, integer-power monomials, affine squares,
and univariate ``sqrt`` — the atoms the Rust kernel implements (``EnvTerm``). A model
using any other lifted family (trilinear / multilinear / ratio / composite convex /
non-``sqrt`` univariate) returns ``None`` here, and the caller keeps the trusted
Python path. Soundness: the produced spec drives the same uniform McCormick
relaxation; the Rust patcher reproduces its envelope rows byte-for-byte (its
differential fixtures), so the native relaxation is bound-neutral with the build.
"""

from __future__ import annotations

from typing import Optional

import numpy as np
import scipy.sparse as sp

_TOL = 1e-12


def _vector_vars_enabled() -> bool:
    """``DISCOPT_NATIVE_KERNEL_VECTOR_VARS``: let the native kernel take models with
    array (vector / matrix) variables. **Default ON since its §5 panel**; ``=0``
    restores the old decline (every array model on the Python spatial tree).

    The kernel works on flat columns and the solver side already maps results back
    through ``_unpack_solution``; only this producer assumed one column per variable
    object, so every model written with ``shape=`` fell to the Python spatial tree.
    With the flag, the spec is built over the C-order flat columns, which is the
    layout ``build_uniform_relaxation`` and ``flat_variable_bounds`` already use:
    an array model and its scalar twin produce byte-identical specs, so the array
    path inherits the scalar path's soundness exactly
    (``test_native_kernel_vector_vars.py`` pins the identity).

    Graduation panel (``scripts/panel_native_kernel_vector_vars.py``, 30 s, OFF/ON
    interleaved ABBA): the 154 in-repo ``.nl`` files give identical specs OFF and ON
    (all scalar); 17 array/scalar twin pairs give byte-identical specs; over 50
    array-variable models -- the #1934 panel's 33 (brute-force oracle), dense integer
    QPs n = 10..20, non-uniform bounds, 2-D variables, scalars around arrays -- total
    wall 151.4 -> 61.5 s, certified 48 -> 50, 35 faster and 0 slower, with every
    incumbent re-verified on the original model and every bound checked against the
    oracle: 969 checks, 0 failures. Dense QP n=15 6.3 -> 1.0 s; ``qp_n18_s1`` and
    ``qp_n20_s1`` certify (6.2 s, 8.8 s) where OFF ends uncertified at 30 s. Models
    outside the kernel's term families (the panel's ``mixed_*``) are declined as
    before and are unchanged.
    """
    from discopt.solver_tuning import _env_flag

    return _env_flag("DISCOPT_NATIVE_KERNEL_VECTOR_VARS", default=True)


def _free_linear_enabled() -> bool:
    """#2011: ``DISCOPT_KERNEL_FREE_LINEAR`` -- let the native kernel take a model
    whose relaxation has a free ORIGINAL column that enters only linearly.

    The guard below declines a spec whenever any column has an infinite bound,
    because an unbounded FACTOR makes a McCormick envelope degenerate (#764,
    tanksize). A column that is no lifted term's factor has no envelope, so that
    reason does not apply to it, yet one such column sent the whole solve to the
    Python tree. Under the flag such a column is admitted with the LP layer's
    ``1e20`` sentinel as its bound; any lifted column, or any original column
    that is a factor of a lifted term, with an infinite bound still declines.
    The kernel's FBBT reads the sentinel as a real infinity and bounds a free
    column through the single-infinite-contributor row deduction
    (``spatial_propagate.rs``); the node LP and the Neumaier-Shcherbina bound
    already treat ``>= 1e20`` as open; OBBT never probes such a column.

    **Graduated (default ON, 2026-10-27); ``=0`` restores the decline.** Census
    (``discopt_benchmarks/scripts/issue2011_free_linear_census.py``, 410 MINLPLib
    instances <= 200 vars/cons with a proven status plus the in-repo corpus, spec
    built at the solver's presolved box with the flag OFF and ON): the flag
    changes the engine on 10 (util, sporttournament14, st_e42, ex14_1_2/5/6,
    pointpack04, autocorr_bern20-15/25-19/25-25); 39 keep declining for a free
    FACTOR (elf, haverly, the ex14_* family, ...); OFF and ON agree on every other
    spec, none of which carries an infinite or ``>= 1e20`` bound. Section 5 panel
    on the 10 (``issue1913_pseudocost_panel.py --flag DISCOPT_KERNEL_FREE_LINEAR``,
    60 s, interleaved): cert-clean, 60 checks, 0 problems; certified +util (61.4 s
    at the limit -> 5.5 s), none lost; where both certify nodes 19 -> 7, wall
    10.7 -> 2.9 s; total wall 334.2 -> 249.0 s; on the 4 neither certifies the
    bound is tighter ON on all 4 (sporttournament14 106 -> 100, autocorr_bern25-19
    -508,536 -> -132,223). Recorded trade-off: on those 4 the time-limit incumbent
    is slightly worse ON (sporttournament14 96 -> 94). performance-plan section 99.
    """
    from discopt.solver_tuning import _env_flag

    return _env_flag("DISCOPT_KERNEL_FREE_LINEAR", default=True)


#: The Rust LP layer's infinite bound. ``f64::INFINITY`` is never passed there.
_LP_INF = 1e20


def build_spatial_kernel_spec(
    model, bounds: Optional[tuple] = None, deadline: Optional[float] = None
) -> Optional[dict]:
    """Return the flat-array ``SpatialKernelSpec`` kwargs for
    ``discopt._rust.solve_spatial_tree_py``, or ``None`` if the model uses a lifted
    term family the native kernel does not implement (caller falls back to Python).

    ``bounds`` optionally overrides the original-variable box with presolved finite
    bounds ``(lb, ub)`` (each length ``n_orig``) — required for models whose raw
    ``.nl`` box is unbounded (e.g. tanksize), where the McCormick relaxation is only
    valid after the solver's FBBT/OBBT presolve.

    ``deadline`` (absolute ``time.perf_counter()``) bounds the two relaxation
    builds: past it the spec is declined (``None``) instead of finished. Each build
    is one walk of the objective, so on a dense quadratic it alone can outlast the
    solve (QPLIB_3361, 163,680 products, ran past 590 s on a 30 s limit here).

    The returned dict also carries two ``meta_``-prefixed keys —
    ``meta_obj_sense_sign`` and ``meta_obj_offset`` — for mapping the kernel's
    internal (minimize-convention) objective/bound back to model units:
    ``model_value = sign * (internal + offset)``. Callers pass the non-``meta_`` keys
    to the kernel; :func:`solve_with_native_kernel` strips them automatically."""
    from discopt._relax.incremental_mccormick import row_support_within
    from discopt._relax.model_utils import flat_variable_bounds
    from discopt._relax.uniform_relax import RelaxationBuildAborted, build_uniform_relaxation
    from discopt.modeling.core import VarType
    from discopt.solver_tuning import current as _tuning

    # Columns 0..n_orig-1 of the relaxation are the model's variables flattened in
    # C order, one per scalar ELEMENT. Without the flag a model with any array
    # variable is declined (the pre-flag behaviour); see ``_vector_vars_enabled``.
    sizes = [int(getattr(v, "size", 1)) for v in model._variables]
    if any(sz != 1 for sz in sizes) and not _vector_vars_enabled():
        return None
    n_orig = sum(sizes)

    if bounds is not None:
        lb = np.asarray(bounds[0], dtype=np.float64).copy()
        ub = np.asarray(bounds[1], dtype=np.float64).copy()
        if lb.shape != (n_orig,) or ub.shape != (n_orig,):
            return None
    else:
        lb, ub = flat_variable_bounds(model)

    def _build(box_lb, box_ub):
        # Skip the separable objective floor and convex-lift OA rows: both are
        # box-dependent rows the closed-form kernel patcher does NOT regenerate (the
        # floor is an objective row; the lift adds extra tangents beyond the
        # McCormick/secant-tangent envelope). Omitting them only loosens the
        # relaxation (a valid lower bound dropped, never invented) and makes each
        # term's envelope match the kernel's regeneration row-for-row. Mirrors the
        # incremental engine's ``_full_build``.
        # Linear-equality RLT rows carry no box data, so they land in the
        # box-INDEPENDENT fixed-row set below and the kernel's per-node patcher
        # (which regenerates only per-term envelope rows) leaves them correct at
        # every node. The bound-factor RLT families are excluded for exactly the
        # opposite reason.
        return build_uniform_relaxation(
            model,
            box=(box_lb, box_ub),
            rlt_lineq=bool(_tuning().rlt_lineq),
            rlt_ineq=bool(_tuning().rlt_ineq),
            skip_separable_floor=True,
            skip_convex_lift=True,
            abort_deadline=deadline,
        )

    # STRUCTURE is identified on a PROBE box with distinct, strictly sign-matched
    # bounds so every McCormick coefficient is nonzero and each term's envelope rows
    # are cleanly separable (exactly 4 per product/square, support = {factors, aux}).
    # At the real box a factor bound of 0 would collapse rows and hide the clean
    # support. The lifted column layout and the box-INDEPENDENT rows (model
    # constraints + linear-definitional aux rows) are identical across boxes, so
    # structure + fixed rows read off the probe build are valid; only the finite
    # column bounds are taken from the real-box build. Mirrors ``_build_structure``.
    root_sign = np.where(lb >= 0.0, 1, np.where(ub <= 0.0, -1, 0))
    lb_p = np.empty(n_orig)
    ub_p = np.empty(n_orig)
    for k in range(n_orig):
        if root_sign[k] < 0:
            lb_p[k], ub_p[k] = -(7.0 + k), -1.0
        else:
            lb_p[k], ub_p[k] = 1.0, 7.0 + k

    # Out of time is the same decline as out of scope: the caller keeps the
    # Python path, which polls the same deadline.
    try:
        rel = _build(lb_p, ub_p)
        milp = rel.model
        if milp._A_ub is None or not getattr(milp, "_objective_bound_valid", True):
            return None
        rel_real = _build(lb, ub)
    except RelaxationBuildAborted:
        return None
    if rel_real.model._A_ub is None:
        return None
    # Soundness guard: if the relaxation has no valid objective bound at the real box
    # — e.g. an unbounded original variable makes a bilinear/monomial aux range
    # infinite, so the McCormick envelope is degenerate — decline rather than emit a
    # spec whose node LP is invalid. (tanksize hits this: its raw .nl box is
    # unbounded and the trusted solver first runs FBBT/presolve to finite bounds;
    # feeding the native kernel presolved bounds is the follow-up. #764.)
    if not getattr(rel_real.model, "_objective_bound_valid", False):
        return None
    # #2011: an infinite bound on a LIFTED column, or with the flag off on any
    # column, declines. Under the flag a free ORIGINAL column passes here and is
    # checked below to be no lifted term's factor.
    _real_inf = np.isinf(np.asarray(rel_real.model._bounds, dtype=np.float64)).any(axis=1)
    free_cols: list[int] = []
    if _real_inf.any():
        if not _free_linear_enabled() or _real_inf[n_orig:].any():
            return None
        free_cols = [int(k) for k in np.flatnonzero(_real_inf[:n_orig])]

    # Decline lifted families the Rust kernel does not implement yet.
    if rel.trilinear_map or rel.multilinear_map or rel.ratio_map or rel.composite_multivar_specs:
        return None
    if any(fname != "sqrt" for (fname, *_rest) in rel.univariate_atom_specs):
        return None
    # VERTICAL TANGENT (#1111): the Rust kernel's ``mccormick_patch::univariate_rows``
    # regenerates the 4-row sqrt envelope UNCONDITIONALLY — it guards ``f`` on the
    # box but not ``f'``, so at ``t_lo == 0`` its tangent-at-``t_lo`` row is
    # ``f'(0) = +inf`` and ``intercept = 0 - inf*0 = NaN``: an LP row with an
    # infinite coefficient and a NaN rhs. The Python build does NOT emit that row
    # (``_emit_1d`` drops the facet, or — under ``DISCOPT_SINGULAR_TANGENT`` —
    # re-anchors it at an interior point the kernel knows nothing about), so the two
    # engines disagree there in BOTH flag states.
    #
    # Today that disagreement is caught only incidentally: the dropped row makes the
    # real-box build one row shorter than the probe build and the shape check below
    # declines. Under the #1111 flag the row counts match again and the incidental
    # guard evaporates, so make the condition EXPLICIT and decline here. Sub-boxes
    # can only raise ``t_lo`` (branching and FBBT tighten), so a spec admitted with
    # ``t_lo > 0`` stays NaN-free at every node.
    for _fname, _w, _var, _coeff, _cst in rel.univariate_atom_specs:
        ta = float(_coeff) * float(lb[int(_var)]) + float(_cst)
        tb = float(_coeff) * float(ub[int(_var)]) + float(_cst)
        if min(ta, tb) <= 0.0:  # sqrt: f'(t) = 0.5/sqrt(t) diverges at t = 0
            return None

    A = sp.csr_matrix(milp._A_ub, dtype=np.float64)
    A.sort_indices()
    b = np.asarray(milp._b_ub, dtype=np.float64).ravel()
    c = np.asarray(milp._c, dtype=np.float64).ravel()
    ncol = int(c.shape[0])
    csc = A.tocsc()
    indptr, indices, data = A.indptr, A.indices, A.data

    _support_within = row_support_within(A, _TOL)

    # #1944: rows the build declares are no term's envelope (constraint-factor RLT)
    # are never claimed, however their support looks; they are fixed rows, checked
    # for box-independence below like every other one.
    _nonenvelope = frozenset(int(r) for r in getattr(rel, "nonenvelope_rows", ()))

    def rows_with_col(cc: int):
        rows = csc.indices[csc.indptr[cc] : csc.indptr[cc + 1]]
        if not _nonenvelope:
            return rows
        return [r for r in rows if int(r) not in _nonenvelope]

    env_rows: set[int] = set()
    # term arrays
    tk: list[int] = []
    ti: list[int] = []
    tj: list[int] = []
    tout: list[int] = []
    tp: list[int] = []
    tcoeff: list[float] = []
    tcst: list[float] = []

    def _claim(aux: int, operands: tuple, want: Optional[int]) -> Optional[list[int]]:
        """Rows owned by this term = rows touching ``aux`` whose support ⊆ operands∪aux.
        Returns the row list, or None if ``want`` is set and the count differs."""
        allowed = set(operands) | {aux}
        rows = [int(r) for r in rows_with_col(aux) if _support_within(int(r), allowed)]
        if want is not None and len(rows) != want:
            return None
        return rows

    claimed_aux: set[int] = set()

    def _push(kind, i, j, out, p, coeff, cst, rows):
        tk.append(kind)
        ti.append(int(i))
        tj.append(int(j))
        tout.append(int(out))
        tp.append(int(p))
        tcoeff.append(float(coeff))
        tcst.append(float(cst))
        env_rows.update(rows)
        claimed_aux.add(int(out))

    # Affine-form products w = A*B (bilinear x_i*x_j AND variable × linear-form / form
    # × form) — every McCormick product the factorable engine emitted, from the
    # relaxer's bilinear_linform_specs. These generalize the single-column bilinear
    # path and cover the multi-column products (tanksize's `x_i·(Σ aₖxₖ)`) that the
    # bilinear_map alone misses. Each becomes a BlfTerm; the kernel regenerates the
    # 4 McCormick rows per box.
    blf_w: list[int] = []
    blf_a_ptr: list[int] = [0]
    blf_a_cols: list[int] = []
    blf_a_coeffs: list[float] = []
    blf_a_const: list[float] = []
    blf_b_ptr: list[int] = [0]
    blf_b_cols: list[int] = []
    blf_b_coeffs: list[float] = []
    blf_b_const: list[float] = []
    for w, a_dict, a_const, b_dict, b_const in rel.bilinear_linform_specs:
        if int(w) in claimed_aux:
            continue
        a_items = sorted((int(k), float(v)) for k, v in a_dict.items())
        b_items = sorted((int(k), float(v)) for k, v in b_dict.items())
        a_cols_t = [k for k, _ in a_items]
        b_cols_t = [k for k, _ in b_items]
        allowed = set(a_cols_t) | set(b_cols_t) | {int(w)}
        rows: Optional[list[int]] = [
            int(r) for r in rows_with_col(int(w)) if _support_within(int(r), allowed)
        ]
        # EXACTLY the 4 McCormick rows the kernel regenerates for this BlfTerm —
        # support containment alone does not identify them (#861). A lifted MODEL
        # CONSTRAINT over the same variables has the same support (``x0*x1 >= 60``
        # becomes ``{aux: -1} <= -60``), and claiming it here excludes it from the
        # fixed rows while the kernel emits only the 4 envelope rows, so the
        # constraint is DROPPED from every node LP. That direction is sound — a
        # dropped relaxation row gives a superset feasible region, hence a weaker
        # but still valid dual bound, and the 6 reachable corpus instances all still
        # certify against ``minlplib.solu`` — but it is a silent tightness loss on a
        # path whose premise is byte-for-byte reproduction of the build.
        #
        # Decline instead, which is what the ``_claim(..., want=4)`` paths below
        # already do for monomials / affine squares; the caller keeps the trusted
        # Python path (whose incremental structure now admits these models, #861 T3).
        # Measured over the corpus: 986 BLF terms claim exactly 4 rows, 38 claim more
        # (13 instances, 6 of them reachable), and NONE claims fewer — so this
        # predicate declines exactly the misclassified terms and no working ones.
        if rows is not None and len(rows) != 4:
            return None
        if not rows:
            return None
        env_rows.update(rows)
        claimed_aux.add(int(w))
        blf_w.append(int(w))
        blf_a_cols.extend(a_cols_t)
        blf_a_coeffs.extend(v for _, v in a_items)
        blf_a_ptr.append(len(blf_a_cols))
        blf_a_const.append(float(a_const))
        blf_b_cols.extend(b_cols_t)
        blf_b_coeffs.extend(v for _, v in b_items)
        blf_b_ptr.append(len(blf_b_cols))
        blf_b_const.append(float(b_const))
    for (i, p), w in rel.monomial_map.items():
        if int(w) in claimed_aux:
            continue
        rows = _claim(w, (i,), 4)
        if rows is None:
            return None
        _push(1, i, -1, w, p, 0.0, 0.0, rows)
    for (i, p), w in rel.univariate_square_map.items():
        # x_i**2 is often registered in BOTH monomial_map and univariate_square_map
        # for the same aux column — claim it once.
        if int(w) in claimed_aux:
            continue
        rows = _claim(w, (i,), 4)
        if rows is None:
            return None
        _push(1, i, -1, w, int(p), 0.0, 0.0, rows)
    for (j, w), (coeff, cst) in rel.affine_square_map.items():
        if int(w) in claimed_aux:
            continue
        rows = _claim(w, (j,), 4)
        if rows is None:
            return None
        _push(2, j, -1, w, 0, coeff, cst, rows)
    for fname, w, var, coeff, cst in rel.univariate_atom_specs:
        if int(w) in claimed_aux:
            continue
        # sqrt only (guarded above). Its concave envelope is up to 4 rows; accept
        # whatever the build emitted for this box (>=1), the kernel regenerates them.
        rows = _claim(w, (var,), None)
        if not rows:
            return None
        _push(3, var, -1, w, 0, coeff, cst, rows)

    # SOUNDNESS VALIDATION: every non-envelope row MUST be box-independent — that is
    # the whole premise of passing it through as a fixed row while the kernel
    # regenerates only the term envelopes per box. Verify by comparing the probe build
    # against the real-box build row-for-row: the lifted structure (and thus row
    # order) is identical across boxes, so a fixed row whose coefficients or rhs differ
    # between the two boxes is actually a box-DEPENDENT envelope the term maps did not
    # capture (e.g. a factorable-intermediate product tanksize lifts beyond its 9
    # bilinear + 3 sqrt terms). Freezing such a row would produce an unsound / infeasible
    # relaxation, so DECLINE — the caller keeps the trusted Python path.
    Ar = sp.csr_matrix(rel_real.model._A_ub, dtype=np.float64)
    Ar.sort_indices()
    br = np.asarray(rel_real.model._b_ub, dtype=np.float64).ravel()
    if Ar.shape != A.shape or br.shape[0] != b.shape[0]:
        return None
    if free_cols:
        # #2011: only purely linear free columns. A free factor of any lifted term
        # (or an infinite coefficient the real-box build derived from its bound)
        # declines, as before.
        factors = set(int(i) for i in ti) | set(int(j) for j in tj if int(j) >= 0)
        factors |= set(blf_a_cols) | set(blf_b_cols)
        if any(k in factors or k in claimed_aux for k in free_cols):
            return None
        if not (np.isfinite(Ar.data).all() and np.isfinite(br).all()):
            return None
        if any(int(r) in env_rows for k in free_cols for r in rows_with_col(k)):
            return None
    rp_indptr, rp_indices, rp_data = Ar.indptr, Ar.indices, Ar.data
    # #1944: bound-factor RLT rows carry the box they were built at. The probe
    # build's copies are valid only in the probe box, so they are never used; the
    # real-box build's copies are valid in every sub-box of ``[lb, ub]``, which is
    # every box the kernel visits (it only ever shrinks the root box). The two
    # builds must agree on WHICH rows these are, or the row correspondence the
    # check below relies on is gone.
    _root_box = frozenset(int(r) for r in getattr(rel, "root_box_rows", ()))
    if _root_box != frozenset(int(r) for r in getattr(rel_real, "root_box_rows", ())):
        return None
    for r in range(A.shape[0]):
        if r in env_rows or r in _root_box:
            continue
        # Same nonzero pattern + values + rhs at both boxes?
        p0, p1 = indptr[r], indptr[r + 1]
        q0, q1 = rp_indptr[r], rp_indptr[r + 1]
        if (p1 - p0) != (q1 - q0):
            return None
        if not np.array_equal(indices[p0:p1], rp_indices[q0:q1]):
            return None
        if not np.allclose(data[p0:p1], rp_data[q0:q1], rtol=1e-9, atol=1e-9):
            return None
        if abs(float(b[r]) - float(br[r])) > 1e-6 * (1.0 + abs(float(br[r]))):
            return None

    # Fixed (box-independent) rows: everything not owned by a term envelope.
    fixed_row_ptr = [0]
    fixed_cols: list[int] = []
    fixed_coeffs: list[float] = []
    fixed_rhs: list[float] = []
    for r in range(A.shape[0]):
        if r in env_rows:
            continue
        if r in _root_box:
            row = Ar.getrow(r)
            fixed_cols.extend(int(cc) for cc in row.indices)
            fixed_coeffs.extend(float(v) for v in row.data)
            fixed_row_ptr.append(len(fixed_cols))
            fixed_rhs.append(float(br[r]))
            continue
        row = A.getrow(r)
        fixed_cols.extend(int(cc) for cc in row.indices)
        fixed_coeffs.extend(float(v) for v in row.data)
        fixed_row_ptr.append(len(fixed_cols))
        fixed_rhs.append(float(b[r]))

    # Bounds come from the REAL-box build's interval propagation (finite) — the
    # safe-bound evaluation needs finite bounds on any column with a nonzero reduced
    # cost, and the factorable intermediate aux are only bounded by these. The column
    # layout is identical to the probe build (structure is box-independent).
    if int(np.size(rel_real.model._c)) != ncol:
        return None
    bnds = np.asarray(rel_real.model._bounds, dtype=np.float64)
    if bnds.shape != (ncol, 2):
        return None
    global_lo = bnds[:, 0].copy()
    global_hi = bnds[:, 1].copy()
    # Original columns take the (possibly presolved) branchable box.
    global_lo[:n_orig] = lb
    global_hi[:n_orig] = ub

    integrality = np.zeros(ncol, dtype=np.int64)
    off = 0
    for v, sz in zip(model._variables, sizes):
        if v.var_type in (VarType.INTEGER, VarType.BINARY):
            integrality[off : off + sz] = 1
        off += sz
    milp_int = getattr(milp, "_integrality", None)
    if milp_int is not None:
        mi = np.asarray(milp_int).ravel()
        if mi.shape[0] == ncol:
            integrality = np.maximum(integrality, (mi != 0).astype(np.int64))

    obbt_candidates = [
        k for k in range(n_orig) if np.isfinite(global_lo[k]) and np.isfinite(global_hi[k])
    ]
    # #2011: an admitted free column carries the LP layer's sentinel, never ``inf``.
    # Under the flag, any other non-finite original bound was not checked above, so
    # it declines (the flag-off path is unchanged).
    if free_cols or _free_linear_enabled():
        _admitted = set(free_cols)
        for k in np.flatnonzero(~(np.isfinite(global_lo) & np.isfinite(global_hi))):
            if int(k) not in _admitted:
                return None
    for k in free_cols:
        if not np.isfinite(global_lo[k]):
            global_lo[k] = -_LP_INF
        if not np.isfinite(global_hi[k]):
            global_hi[k] = _LP_INF

    if c.shape[0] != ncol:
        return None

    return dict(
        n_cols=ncol,
        n_orig=n_orig,
        c=c,
        integrality=integrality,
        global_lo=global_lo,
        global_hi=global_hi,
        fixed_row_ptr=np.asarray(fixed_row_ptr, dtype=np.int64),
        fixed_cols=np.asarray(fixed_cols, dtype=np.int64),
        fixed_coeffs=np.asarray(fixed_coeffs, dtype=np.float64),
        fixed_rhs=np.asarray(fixed_rhs, dtype=np.float64),
        term_kind=np.asarray(tk, dtype=np.int64),
        term_i=np.asarray(ti, dtype=np.int64),
        term_j=np.asarray(tj, dtype=np.int64),
        term_out=np.asarray(tout, dtype=np.int64),
        term_p=np.asarray(tp, dtype=np.int64),
        term_coeff=np.asarray(tcoeff, dtype=np.float64),
        term_cst=np.asarray(tcst, dtype=np.float64),
        blf_w=np.asarray(blf_w, dtype=np.int64),
        blf_a_ptr=np.asarray(blf_a_ptr, dtype=np.int64),
        blf_a_cols=np.asarray(blf_a_cols, dtype=np.int64),
        blf_a_coeffs=np.asarray(blf_a_coeffs, dtype=np.float64),
        blf_a_const=np.asarray(blf_a_const, dtype=np.float64),
        blf_b_ptr=np.asarray(blf_b_ptr, dtype=np.int64),
        blf_b_cols=np.asarray(blf_b_cols, dtype=np.int64),
        blf_b_coeffs=np.asarray(blf_b_coeffs, dtype=np.float64),
        blf_b_const=np.asarray(blf_b_const, dtype=np.float64),
        obbt_candidates=np.asarray(obbt_candidates, dtype=np.int64),
        # Metadata (stripped before the kernel call): map the kernel's internal
        # minimize-convention value back to model units — model = sign*(internal+off).
        meta_obj_sense_sign=float(getattr(rel, "obj_sense_sign", 1.0)),
        meta_obj_offset=float(getattr(rel, "obj_offset", 0.0)),
    )


def solve_with_native_kernel(model, bounds: Optional[tuple] = None, **config):
    """Convenience: produce the spec and run the native kernel. Returns the result
    dict from ``solve_spatial_tree_py`` (with ``meta_*`` echoed back), or ``None`` if
    the model is unsupported."""
    spec = build_spatial_kernel_spec(model, bounds=bounds)
    if spec is None:
        return None
    from discopt import _rust

    meta = {k: spec.pop(k) for k in list(spec) if k.startswith("meta_")}
    from discopt import _timing

    with _timing.charge("rust"):
        res = _rust.solve_spatial_tree_py(**spec, **config)
    res.update(meta)
    return res
